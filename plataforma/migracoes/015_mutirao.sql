-- 015 (v2.13.0): mutirão de fichas históricas.
-- Aditiva e idempotente: uma tabela nova e uma coluna sem valor padrão. Nenhum dado existente é alterado.
-- As fichas do mutirão são identificadas por membros.origem = 'mutirao:<lote>:<sufixo>'.

create table if not exists public.mutirao_lotes (
  id            bigint generated by default as identity primary key,
  nome          varchar(120) not null,
  justificativa text         not null,
  codigo        varchar(10)  not null unique,
  valido_ate    timestamptz  not null,
  criado_por    varchar(120),
  criado_em     timestamptz  default now()
);
alter table public.membros add column if not exists credo_email_em timestamptz;

-- Mesma proteção das demais tabelas: só o servidor (conexão direta) acessa; a API pública do Supabase não.
alter table public.mutirao_lotes enable row level security;
