-- 012 (v2.9.0): Coordenação por período ou evento e inativação/exclusão de membros com justificativa.
-- Aditiva e idempotente: só cria colunas novas (com valor padrão) e uma tabela de histórico.
-- Nenhum dado existente é alterado ou removido.

-- Cada linha de usuario_setores passa a ser uma designação de Coordenação com tipo e prazo.
-- As designações que já existem ficam como 'permanente' (comportamento atual).
alter table public.usuario_setores add column if not exists tipo varchar(20) not null default 'permanente';  -- permanente | periodo | evento
alter table public.usuario_setores add column if not exists inicio date;
alter table public.usuario_setores add column if not exists fim date;
alter table public.usuario_setores add column if not exists evento_id varchar(64);
alter table public.usuario_setores add column if not exists observacao text;
alter table public.usuario_setores add column if not exists disponibilidade boolean not null default false;
alter table public.usuario_setores add column if not exists criado_por varchar(120);
alter table public.usuario_setores add column if not exists criado_em timestamptz default now();

-- Histórico das coordenações encerradas (pelo prazo ou por decisão da Secretaria/Adm)
create table if not exists public.coordenacoes_historico (
  id                   bigint generated by default as identity primary key,
  usuario_id           bigint,
  usuario_nome         varchar(160),
  departamento_id      varchar(64),
  setor_nome           varchar(160),
  tipo                 varchar(20),
  inicio               date,
  fim                  date,
  evento_id            varchar(64),
  evento_titulo        varchar(200),
  observacao           text,
  criado_por           varchar(120),
  criado_em            timestamptz,
  encerrado_em         timestamptz not null default now(),
  encerrado_por        varchar(120),
  motivo_encerramento  text
);
create index if not exists coordenacoes_historico_usuario on public.coordenacoes_historico (usuario_id);

-- Membros: inativação e exclusão (lixeira) com justificativa obrigatória
alter table public.membros add column if not exists inativado_em timestamptz;
alter table public.membros add column if not exists inativado_por varchar(120);
alter table public.membros add column if not exists motivo_inativacao text;
alter table public.membros add column if not exists excluido_em timestamptz;
alter table public.membros add column if not exists excluido_por varchar(120);
alter table public.membros add column if not exists motivo_exclusao text;
alter table public.membros add column if not exists status_anterior varchar(40);
alter table public.membros add column if not exists login_suspenso boolean not null default false;

alter table public.coordenacoes_historico enable row level security;
do $$
begin
  if exists (select 1 from pg_roles where rolname = 'anon') then
    execute 'revoke all on public.coordenacoes_historico from anon, authenticated';
  end if;
end $$;
