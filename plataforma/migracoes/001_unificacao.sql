begin;

create table if not exists public.membros (
  id                         bigint generated by default as identity primary key,
  data_registro              date,
  nome_completo              text not null,
  endereco text, bairro text, cidade text, cep text,
  data_nascimento            date,
  naturalidade text, sexo text, estado_civil text, conjuge text,
  filhos                     jsonb default '[]'::jsonb,
  email text, telefone text, whatsapp text,
  escolaridade text, formacao_academica text, profissao text, empresa text,
  batizado text, data_batismo date,
  congregava_antes text, onde_congregava text, area_ministerial text, interesse_batismo_familia text,
  credo_aceito               boolean not null default false,
  nome_assinante text, assinatura_rubrica text,
  data_assinatura            timestamptz,
  hash_autenticidade text,
  ocr_documento_nome text,
  foto_3x4 text,
  lgpd_consentimento         boolean not null default false,
  lgpd_versao_termo text,
  lgpd_data_consentimento    timestamptz,
  lgpd_ip_origem text,
  status_lgpd text default 'Consentimento Ativo',
  status                     text not null default 'Aguardando Análise',
  validado_por text,
  data_validacao             timestamptz,
  link_credo_enviado         boolean not null default false,
  observacoes text,
  origem text,
  criado_em                  timestamptz default now(),
  atualizado_em              timestamptz default now()
);
create index if not exists membros_status_idx on public.membros (status);
create index if not exists membros_email_idx on public.membros (lower(email));
create unique index if not exists membros_origem_uq on public.membros (origem) where origem is not null and origem <> 'novo';

create table if not exists public.usuarios (
  id                  bigint generated by default as identity primary key,
  nome                text not null,
  email               text not null unique,
  senha_hash          text not null,
  salt                text not null,
  iteracoes           integer not null default 600000,
  perfil              text not null default 'membro' check (perfil in ('membro','secretaria','admin')),
  ativo               boolean not null default true,
  trocar_senha        boolean not null default false,
  membro_id           bigint references public.membros(id) on delete set null,
  tentativas_falhas   integer not null default 0,
  bloqueado_ate       timestamptz,
  ultimo_login        timestamptz,
  origem              text,
  criado_em           timestamptz default now()
);

create table if not exists public.membro_setores (
  id               bigint generated by default as identity primary key,
  membro_id        bigint not null references public.membros(id) on delete cascade,
  departamento_id  bigint not null,
  funcao           text default 'Voluntário',
  constraint uq_membro_setor unique (membro_id, departamento_id)
);

create table if not exists public.auditoria (
  id            bigint generated by default as identity primary key,
  criado_em     timestamptz default now(),
  usuario_id    bigint,
  usuario_nome  text,
  acao          text not null,
  recurso       text,
  detalhes      text,
  ip            text
);
create index if not exists auditoria_criado_idx on public.auditoria (criado_em desc);

-- Colunas novas e OPCIONAIS nas tabelas da Agenda (não afetam o Streamlit)
alter table public.eventos    add column if not exists descricao text;
alter table public.eventos    add column if not exists local text;
alter table public.inscricoes add column if not exists membro_id bigint;

-- Tabelas novas ficam fechadas para a chave pública (anon/authenticated).
-- A plataforma acessa pelo servidor com a conexão do banco, nunca pelo navegador.
alter table public.membros        enable row level security;
alter table public.usuarios       enable row level security;
alter table public.membro_setores enable row level security;
alter table public.auditoria      enable row level security;
revoke all on public.membros, public.usuarios, public.membro_setores, public.auditoria from anon, authenticated;

commit;
