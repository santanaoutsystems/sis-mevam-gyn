-- 013 (v2.11.0): Dia do Profissional, intenção de dízimo, pesquisa mensal de necessidades e Instituto.
-- Aditiva e idempotente: só cria colunas (com valor padrão) e tabelas novas. Nenhum dado existente é alterado.

alter table public.membros add column if not exists dia_profissional varchar(5);
alter table public.membros add column if not exists homenagem_profissional boolean not null default true;
alter table public.membros add column if not exists deseja_dizimista varchar(20);
alter table public.membros add column if not exists dia_dizimo integer;

-- Pesquisa mensal: a resposta não guarda quem respondeu; o controle não guarda o que foi respondido
create table if not exists public.necessidades_controle (
  mes        varchar(7) not null,
  usuario_id bigint     not null references public.usuarios(id) on delete cascade,
  primary key (mes, usuario_id)
);
create table if not exists public.necessidades_respostas (
  id                 bigint generated by default as identity primary key,
  mes                varchar(7) not null,
  faixa              varchar(30),
  comentario         text,
  nenhuma            boolean not null default false,
  contato_usuario_id bigint references public.usuarios(id) on delete set null
);
create index if not exists necessidades_respostas_mes on public.necessidades_respostas (mes);
create table if not exists public.necessidades_itens (
  id          bigint generated by default as identity primary key,
  resposta_id bigint not null references public.necessidades_respostas(id) on delete cascade,
  categoria   varchar(30) not null,
  intensidade integer not null default 2
);

-- Instituto: estrutura reservada (sem telas de cadastro ainda)
create table if not exists public.instituto_cursos (
  id        bigint generated by default as identity primary key,
  nome      varchar(160) not null,
  descricao text,
  ativo     boolean not null default true,
  criado_em timestamptz default now()
);
create table if not exists public.instituto_turmas (
  id       bigint generated by default as identity primary key,
  curso_id bigint not null references public.instituto_cursos(id) on delete cascade,
  nome     varchar(160) not null,
  inicio   date,
  fim      date
);
create table if not exists public.instituto_matriculas (
  id        bigint generated by default as identity primary key,
  turma_id  bigint not null references public.instituto_turmas(id) on delete cascade,
  membro_id bigint not null references public.membros(id) on delete cascade,
  situacao  varchar(30) not null default 'Matriculado',
  constraint instituto_matricula_unica unique (turma_id, membro_id)
);

-- Sem acesso pela chave pública do Supabase (o app usa a conexão do servidor)
alter table public.necessidades_controle enable row level security;
alter table public.necessidades_respostas enable row level security;
alter table public.necessidades_itens enable row level security;
alter table public.instituto_cursos enable row level security;
alter table public.instituto_turmas enable row level security;
alter table public.instituto_matriculas enable row level security;
do $$
begin
  if exists (select 1 from pg_roles where rolname = 'anon') then
    execute 'revoke all on public.necessidades_controle, public.necessidades_respostas, public.necessidades_itens, '
            'public.instituto_cursos, public.instituto_turmas, public.instituto_matriculas from anon, authenticated';
  end if;
end $$;
