alter table public.usuarios drop constraint if exists usuarios_perfil_check;
alter table public.usuarios add constraint usuarios_perfil_check
  check (perfil in ('membro','coordenacao','secretaria','admin'));

create table if not exists public.usuario_setores (
  id               bigint generated by default as identity primary key,
  usuario_id       bigint not null references public.usuarios(id) on delete cascade,
  departamento_id  bigint not null,
  constraint uq_usuario_setor unique (usuario_id, departamento_id)
);

-- Fechada para a chave pública, como as demais tabelas novas.
alter table public.usuario_setores enable row level security;
revoke all on public.usuario_setores from anon, authenticated;
