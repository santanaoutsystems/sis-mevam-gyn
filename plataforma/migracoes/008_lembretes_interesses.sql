-- v2.6.0: foto opcional no pré-cadastro (lembretes por e-mail) e setores em que o membro deseja servir.
-- Aditiva e idempotente: só cria tabelas e índices; não altera nem apaga dados.
create table if not exists public.lembretes_cadastro (
  id          bigint generated by default as identity primary key,
  membro_id   bigint not null references public.membros(id) on delete cascade,
  etapa       varchar(10) not null,
  enviado_em  timestamptz not null default now(),
  resultado   text,
  constraint lembretes_cadastro_unico unique (membro_id, etapa)
);

create table if not exists public.membro_interesses (
  id         bigint generated by default as identity primary key,
  membro_id  bigint not null references public.membros(id) on delete cascade,
  setor      varchar(80) not null,
  criado_em  timestamptz not null default now(),
  constraint membro_interesses_unico unique (membro_id, setor)
);
create index if not exists membro_interesses_setor on public.membro_interesses (setor);

-- Mesma proteção das tabelas novas: só o app (conexão direta) acessa
alter table public.lembretes_cadastro enable row level security;
alter table public.membro_interesses enable row level security;
do $$
begin
  if exists (select 1 from pg_roles where rolname = 'anon') then
    execute 'revoke all on public.lembretes_cadastro from anon, authenticated';
    execute 'revoke all on public.membro_interesses from anon, authenticated';
  end if;
end $$;

-- Pesquisa de satisfação do e-mail de boas-vindas (uma resposta por membro)
create table if not exists public.pesquisa_satisfacao (
  id             bigint generated by default as identity primary key,
  membro_id      bigint not null unique references public.membros(id) on delete cascade,
  resposta       varchar(20) not null,
  respondido_em  timestamptz not null default now()
);
alter table public.pesquisa_satisfacao enable row level security;
do $$
begin
  if exists (select 1 from pg_roles where rolname = 'anon') then
    execute 'revoke all on public.pesquisa_satisfacao from anon, authenticated';
  end if;
end $$;
