-- 014 (v2.12.0): INTEGRA como porta de entrada.
-- Aditiva e idempotente: só cria colunas (sem valor padrão) e uma tabela nova. Nenhum dado existente é alterado.
-- Fichas antigas ficam com integra_situacao vazia até responderem à campanha de atualização.

alter table public.membros add column if not exists integra_situacao varchar(30);
alter table public.membros add column if not exists integra_data date;
alter table public.membros add column if not exists integra_turma_id integer;
alter table public.membros add column if not exists integra_registrado_por varchar(120);
alter table public.membros add column if not exists integra_registrado_em timestamptz;
alter table public.membros add column if not exists integra_justificativa text;
alter table public.membros add column if not exists integra_pedido_em timestamptz;
alter table public.membros add column if not exists integra_prazo date;
alter table public.membros add column if not exists integra_lembrete_em timestamptz;

create table if not exists public.integra_turmas (
  id                bigint generated by default as identity primary key,
  nome              varchar(120) not null,
  data_conclusao    date         not null,
  local             varchar(120),
  codigo            varchar(10)  not null unique,
  codigo_valido_ate timestamptz  not null,
  criado_por        varchar(120),
  criado_em         timestamptz  default now()
);
create index if not exists membros_integra_situacao on public.membros (integra_situacao);

-- Mesma proteção das demais tabelas: só o servidor (conexão direta) acessa; a API pública do Supabase não.
alter table public.integra_turmas enable row level security;
