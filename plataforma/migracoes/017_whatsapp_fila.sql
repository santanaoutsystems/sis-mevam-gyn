-- 017 (v2.16.0): fila do WhatsApp da Secretaria (pedidos de complemento e do Credo sem WhatsApp Business).
-- Aditiva e idempotente: uma tabela nova e colunas sem valor padrão. Nenhum dado existente é alterado.

create table if not exists public.whatsapp_envios (
  id           bigint generated by default as identity primary key,
  membro_id    bigint       not null,
  lote_id      bigint,
  tipo         varchar(20)  not null,
  etapa        varchar(10)  not null,
  conta_cota   boolean      not null default true,
  modelo       integer,
  enviado_em   timestamptz  not null,
  enviado_por  varchar(120)
);
create index if not exists whatsapp_envios_membro_idx on public.whatsapp_envios (membro_id);
create index if not exists whatsapp_envios_enviado_idx on public.whatsapp_envios (enviado_em);
alter table public.membros add column if not exists whatsapp_situacao varchar(20);
alter table public.membros add column if not exists whatsapp_situacao_em timestamptz;
alter table public.mutirao_lotes add column if not exists whatsapp_modo varchar(10);

-- Mesma proteção das demais tabelas: só o servidor (conexão direta) acessa; a API pública do Supabase não.
alter table public.whatsapp_envios enable row level security;
