-- Regularização de fichas impressas antigas: ficha escaneada + links exclusivos com prazo.
-- Aditiva e idempotente: só cria colunas, tabela e índices; não altera nem apaga dados.
alter table public.membros add column if not exists ficha_escaneada text;
alter table public.membros add column if not exists ficha_escaneada_em timestamptz;
alter table public.membros add column if not exists ficha_escaneada_por text;

create table if not exists public.regularizacoes (
  id            bigint generated by default as identity primary key,
  membro_id     bigint not null references public.membros(id) on delete cascade,
  segredo       varchar(64) not null,
  criado_em     timestamptz not null default now(),
  criado_por    text,
  expira_em     timestamptz not null,
  enviado_em    timestamptz,
  canais        text,
  concluido_em  timestamptz,
  revogado      boolean not null default false,
  desfecho      text
);
create index if not exists regularizacoes_membro on public.regularizacoes (membro_id);
-- Mesma proteção das tabelas novas: só o app (conexão direta) acessa
alter table public.regularizacoes enable row level security;
do $$
begin
  if exists (select 1 from pg_roles where rolname = 'anon') then
    execute 'revoke all on public.regularizacoes from anon, authenticated';
  end if;
end $$;
