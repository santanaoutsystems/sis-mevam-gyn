-- v2.8.0: Aniversariantes (aviso 1 dia antes, calendário, mensagem especial no dia).
-- Aditiva e idempotente: só cria tabelas, índices e colunas novas com valor padrão; não altera nem apaga dados.

-- Recusa de homenagem (LGPD): todos participam por padrão; o membro pode desligar
alter table public.membros add column if not exists homenagem_aniversario boolean not null default true;
-- Resumo diário por e-mail dos avisos (cada usuário pode desligar)
alter table public.usuarios add column if not exists email_avisos boolean not null default true;

-- Avisos do sino e da janela (um por usuário, tipo, membro e dia)
create table if not exists public.avisos (
  id           bigint generated by default as identity primary key,
  usuario_id   bigint not null references public.usuarios(id) on delete cascade,
  tipo         varchar(30) not null,
  membro_id    bigint references public.membros(id) on delete cascade,
  referencia   date not null,
  janela       boolean not null default false,
  criado_em    timestamptz not null default now(),
  lido_em      timestamptz,
  email_em     timestamptz,
  constraint avisos_unico unique (usuario_id, tipo, membro_id, referencia)
);
create index if not exists avisos_usuario_ref on public.avisos (usuario_id, referencia);

-- Modelos de mensagem de aniversário (Secretaria e Adm)
create table if not exists public.mensagens_modelo (
  id             bigint generated by default as identity primary key,
  tipo           varchar(30) not null default 'aniversario',
  titulo         varchar(80) not null,
  texto          text not null,
  ativo          boolean not null default true,
  padrao         boolean not null default false,
  criado_por     varchar(120),
  atualizado_em  timestamptz not null default now()
);

-- Mensagens enviadas (marca o ✔ no calendário). "chave" só é preenchida no e-mail automático (trava 1 por ano).
create table if not exists public.aniversario_envios (
  id           bigint generated by default as identity primary key,
  membro_id    bigint not null references public.membros(id) on delete cascade,
  ano          integer not null,
  canal        varchar(20) not null,
  usuario_id   bigint references public.usuarios(id) on delete set null,
  usuario_nome varchar(120),
  enviado_em   timestamptz not null default now(),
  resultado    text,
  chave        varchar(60) unique
);
create index if not exists aniversario_envios_membro_ano on public.aniversario_envios (membro_id, ano);

-- Mesma proteção das tabelas novas: só o app (conexão direta) acessa
alter table public.avisos enable row level security;
alter table public.mensagens_modelo enable row level security;
alter table public.aniversario_envios enable row level security;
do $$
begin
  if exists (select 1 from pg_roles where rolname = 'anon') then
    execute 'revoke all on public.avisos from anon, authenticated';
    execute 'revoke all on public.mensagens_modelo from anon, authenticated';
    execute 'revoke all on public.aniversario_envios from anon, authenticated';
  end if;
end $$;
