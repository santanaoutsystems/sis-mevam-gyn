-- v2.7.0: Central de Relatórios — "Meus filtros" (combinações de filtros salvas por cada usuário).
-- Aditiva e idempotente: só cria a tabela e o índice; não altera nem apaga dados.
create table if not exists public.relatorios_salvos (
  id          bigint generated by default as identity primary key,
  usuario_id  bigint not null references public.usuarios(id) on delete cascade,
  nome        varchar(80) not null,
  relatorio   varchar(40) not null,
  consulta    text not null default '',
  criado_em   timestamptz not null default now()
);
create index if not exists relatorios_salvos_usuario on public.relatorios_salvos (usuario_id);

-- Mesma proteção das tabelas novas: só o app (conexão direta) acessa
alter table public.relatorios_salvos enable row level security;
do $$
begin
  if exists (select 1 from pg_roles where rolname = 'anon') then
    execute 'revoke all on public.relatorios_salvos from anon, authenticated';
  end if;
end $$;
